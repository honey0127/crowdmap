    std::string findNearestArea(double lat, double lng) {
        double minDist = 1e9;
        std::string nearest;
        for (auto& [name, coord] : seoulAreas) {
            double dLat = lat - coord.first;
            double dLng = lng - coord.second;
            double d = dLat * dLat + dLng * dLng;
            if (d < minDist) {
                minDist = d;
                nearest = name;
            }
        }
        // 약 3km 이내(0.0009 ≈ 약 3km^2)면 매칭으로 인정
        return (minDist < 0.0009) ? nearest : "";
    }

    int seoulLevelToInt(const std::string& lvl) {
        if (lvl == "여유")       return 1;
        if (lvl == "보통")       return 2;
        if (lvl == "약간 붐빔")  return 3;
        if (lvl == "붐빔")       return 4;
        return 1;
    }

    std::string urlEncode(const std::string& s) {
        CURL* curl = curl_easy_init();
        char* encoded = curl_easy_escape(curl, s.c_str(), s.length());
        std::string result(encoded);
        curl_free(encoded);
        curl_easy_cleanup(curl);
        return result;
    }

    static size_t writeCallback(void* contents, size_t size,
                                size_t nmemb, std::string* userp) {
        userp->append((char*)contents, size * nmemb);
        return size * nmemb;
    }

    std::string httpGet(const std::string& url) {
        CURL* curl = curl_easy_init();
        std::string response;
        if (curl) {
            curl_easy_setopt(curl, CURLOPT_URL, url.c_str());
            curl_easy_setopt(curl, CURLOPT_WRITEFUNCTION, writeCallback);
            curl_easy_setopt(curl, CURLOPT_WRITEDATA, &response);
            curl_easy_setopt(curl, CURLOPT_TIMEOUT, 5L);
            curl_easy_perform(curl);
            curl_easy_cleanup(curl);
        }
        return response;
    }
